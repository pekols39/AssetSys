<?php

declare(strict_types=1);

require_once dirname(__DIR__, 3) . '/app/bootstrap.php';

use App\Core\Auth;
use App\Core\Database;
use App\Helpers\Csrf;
use App\Middleware\AuthMiddleware;
use App\Services\AdministrationUserService;
use App\Services\AuthorizationService;

AuthMiddleware::handle();

$authorization = new AuthorizationService();
$currentUser = $authorization->currentUser();

if ($currentUser === null) {
    Auth::logout();

    header('Location: ' . base_url('/public/login.php'));
    exit;
}

if (!$authorization->isAdministrator()) {
    http_response_code(403);
    exit('Access denied. Administrator access required.');
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    header('Allow: POST');
    exit('Method not allowed.');
}

$csrfToken = $_POST[CSRF_TOKEN_NAME] ?? null;

if (!is_string($csrfToken) || !Csrf::validate($csrfToken)) {
    http_response_code(403);
    exit('Invalid security token.');
}

/**
 * Read a scalar POST value without accepting arrays.
 */
$getString = static function (string $key): ?string {
    $value = $_POST[$key] ?? null;

    return is_string($value) ? $value : null;
};

$firstName = trim($getString('first_name') ?? '');
$middleName = trim($getString('middle_name') ?? '');
$lastName = trim($getString('last_name') ?? '');
$username = trim($getString('username') ?? '');
$email = trim($getString('email') ?? '');
$position = trim($getString('position') ?? '');

$initialPassword = $getString('initial_password');
$confirmPassword = $getString('confirm_password');

$roleId = filter_var(
    $_POST['role_id'] ?? null,
    FILTER_VALIDATE_INT
);


if (
    $firstName === ''
    || $lastName === ''
    || $username === ''
    || $email === ''
    || $position === ''
    || $initialPassword === null
    || $confirmPassword === null
) {
    http_response_code(422);
    exit('Please complete all required fields.');
}

if (
    $roleId === false
    || $roleId === null
    || $roleId <= 0
) {
    http_response_code(422);
    exit('Please select a valid role.');
}

if (
    mb_strlen($firstName) > 100
    || mb_strlen($middleName) > 100
    || mb_strlen($lastName) > 100
    || strlen($username) > 100
    || strlen($email) > 150
    || mb_strlen($position) > 150
) {
    http_response_code(422);
    exit('One or more fields exceed the allowed length.');
}

if (!preg_match('/^[A-Za-z0-9._-]+$/', $username)) {
    http_response_code(422);
    exit(
        'Username may only contain letters, numbers, dots, '
        . 'underscores, and hyphens.'
    );
}

if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
    http_response_code(422);
    exit('Please provide a valid email address.');
}

if (
    strlen($initialPassword) < 12
    || strlen($initialPassword) > 72
) {
    http_response_code(422);
    exit(
        'The initial password must be between 12 and 72 bytes long.'
    );
}

if ($initialPassword !== $confirmPassword) {
    http_response_code(422);
    exit('The initial password and confirmation do not match.');
}

$db = Database::connection();

/*
 * Only allow active Asset Manager and Property Custodian roles.
 */
$stmt = $db->prepare(
    'SELECT id
     FROM roles
     WHERE id = :role_id
       AND is_active = 1
       AND name IN (
           \'Asset Manager\',
           \'Property Custodian\'
       )
     LIMIT 1'
);

$stmt->execute([
    'role_id' => $roleId,
]);

if ($stmt->fetchColumn() === false) {
    http_response_code(422);
    exit('Only Asset Manager and Property Custodian roles are allowed.');
}

/*
 * Account creation through this form is restricted to Finance.
 */
$financeDepartmentId = 3;

$stmt = $db->prepare(
    'SELECT id
     FROM departments
     WHERE id = :department_id
       AND LOWER(TRIM(name)) = \'finance\'
       AND is_active = 1
     LIMIT 1'
);

$stmt->execute([
    'department_id' => $financeDepartmentId,
]);

if ($stmt->fetchColumn() === false) {
    http_response_code(500);
    exit('The active Finance department could not be found.');
}

/*
 * Prevent duplicate usernames and emails.
 * Employee numbers are generated by AdministrationUserService.
 */
$stmt = $db->prepare(
    'SELECT id
     FROM users
     WHERE username = :username
        OR email = :email
     LIMIT 1'
);

$stmt->execute([
    'username' => $username,
    'email' => $email,
]);

if ($stmt->fetchColumn() !== false) {
    http_response_code(409);
    exit(
        'Another account already uses this username or email address.'
    );
}

try {
    $userService = new AdministrationUserService();

    $newUserId = $userService->create([
        'role_id' => $roleId,
        'position' => $position,
        'first_name' => $firstName,
        'middle_name' => $middleName !== ''
            ? $middleName
            : null,
        'last_name' => $lastName,
        'username' => $username,
        'email' => $email,
        'initial_password' => $initialPassword,
    ]);
} catch (\PDOException $e) {
    error_log(
        'Administration account creation database error: '
        . $e->getMessage()
    );

    if ($e->getCode() === '23000') {
        http_response_code(409);
        exit(
            'An account already uses a unique value. '
            . 'Please review the username and email address.'
        );
    }

    http_response_code(500);
    exit('Unable to create the user account.');
} catch (\Throwable $e) {
    error_log(
        'Administration account creation error: '
        . $e->getMessage()
    );

    http_response_code(500);
    exit('Unable to create the user account.');
}

header(
    'Location: '
    . base_url(
        '/public/administration/users/view.php?id='
        . $newUserId
        . '&success=1'
    )
);

exit;